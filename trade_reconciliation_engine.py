import pandas as pd

# 1. Create the Internal Data (Citadel's Ledger)
data_internal = {
    'TradeID': [101, 102, 103],
    'Symbol': ['AAPL', 'TSLA', 'GOOG'],
    'Quantity': [100, 50, 10],
    'Price': [150.00, 200.00, 2800.00],
    'Status': ['Settled', 'Settled', 'Pending']
}
df_internal = pd.DataFrame(data_internal)

# 2. Create the External Data (Bank's Statement)
# Note the intentional errors: TSLA qty is 40 (break), GOOG is missing (break)
data_bank = {
    'RefID': [101, 102, 104],
    'Ticker': ['AAPL', 'TSLA', 'MSFT'],
    'Qty': [100, 40, 20],
    'ExecPrice': [150.00, 200.00, 300.00],
    'Fee': [5.00, 5.00, 2.00]
}
df_bank = pd.DataFrame(data_bank)

print("Files created successfully in memory!")
df_internal.head()

# 1. Rename columns to match (Normalization)
# We want the Bank data to look like Internal data
df_bank = df_bank.rename(columns={'RefID': 'TradeID', 'Ticker': 'Symbol', 'Qty': 'Quantity', 'ExecPrice': 'Price'})

# 2. Merge the two datasets
# "outer" join ensures we see trades that exist in one but not the other
df_merged = pd.merge(df_internal, df_bank, on='TradeID', how='outer', suffixes=('_Internal', '_Bank'))

# 3. Find the Breaks (Where columns don't match)
breaks = df_merged[
    (df_merged['Quantity_Internal'] != df_merged['Quantity_Bank']) |
    (df_merged['Price_Internal'] != df_merged['Price_Bank']) |
    (df_merged['Symbol_Internal'] != df_merged['Symbol_Bank'])
]

# 4. Display the Report
print(f"Found {len(breaks)} breaks found in reconciliation.")
breaks[['TradeID', 'Symbol_Internal', 'Symbol_Bank', 'Quantity_Internal', 'Quantity_Bank']]